// Runs after `astro build`:
//  1. copies the PHP contact-form handler (server/api) into dist/api
//  2. writes dist/.htaccess: HTTPS + apex redirect, old WordPress URL redirects, caching, headers
//  3. writes dist/version.txt (which commit is live)
import { cpSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dist = join(root, "dist");
const services = JSON.parse(readFileSync(join(root, "src/data/services.json"), "utf8"));

cpSync(join(root, "server/api"), join(dist, "api"), {
  recursive: true,
  filter: (src) => !/config\.local\.php$|\/private\/data/.test(src),
});
rmSync(join(dist, "api/private/data"), { recursive: true, force: true });

// Old WordPress pages that no longer exist as such: [regex without leading slash, target]
const pageRedirects = [
  ["(blog|news-grid|news-list)/?", "/news/"],
  ["make-an-appointment/?", "/contact/?reason=call"],
  ["company-overview/(our-team-grid|our-team-list|company-history|our-approach)/?", "/company-overview/"],
  ["(staff|team)(/.*)?", "/company-overview/"],
  ["careers_archive(/.*)?", "/company-overview/careers/"],
  ["(category|author|tag)/.*", "/news/"],
  ["(feed|comments/feed)/?", "/news/"],
  ["service/?", "/services/"],
  ["(contact-us|contacts|get-in-touch)/?", "/contact/"],
  ["(about|about-us)/?", "/company-overview/"],
];
const known = new Set(services.map((s) => s.slug));

const htaccess = `# Generated by scripts/postbuild.mjs. Edit that file, not this one.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8

<IfModule mod_rewrite.c>
RewriteEngine On

# Certificate checks (Let's Encrypt) must be answered over plain HTTP on every host, never redirected
RewriteRule ^\\.well-known/acme-challenge/ - [L]

# HTTPS and apex domain (works behind Cloudflare or another proxy too)
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteCond %{HTTP_HOST} ^(www\\.)?othaimeengrp\\.com$ [NC]
RewriteRule ^ https://othaimeengrp.com%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\.othaimeengrp\\.com$ [NC]
RewriteRule ^ https://othaimeengrp.com%{REQUEST_URI} [R=301,L]

# Old WordPress endpoints: gone for good
RewriteRule ^(wp-admin|wp-login\\.php|xmlrpc\\.php|wp-json|wp-includes)(/.*)?$ - [G,L]
RewriteCond %{QUERY_STRING} (^|&)(p|page_id|post_type|s)= [NC]
RewriteRule ^$ /? [R=301,L]

# Old pages
${pageRedirects.map(([from, to]) => `RewriteRule ^${from}$ ${to} [R=301,L]`).join("\n")}
# Unknown old service slugs go to the services list (known ones exist as pages)
RewriteCond %{REQUEST_URI} !^/service/(${[...known].join("|")})/?$
RewriteRule ^service/ /services/ [R=301,L]

# Old media: logos are kept at their old paths (email signatures load them); the rest is gone
RewriteCond %{REQUEST_FILENAME} !-f
RewriteRule ^wp-content/ - [G,L]

# Directories without a trailing slash
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^(.*[^/])$ /$1/ [R=301,L]
</IfModule>

<IfModule mod_headers.c>
  # Keep the temporary hosting domain (and any other non-production host) out of Google
  <If "%{HTTP_HOST} !~ /^(www\\.)?othaimeengrp\\.com$/">
    Header always set X-Robots-Tag "noindex, nofollow"
  </If>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set Strict-Transport-Security "max-age=31536000"
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\\.(webp|png|jpg|jpeg|svg|woff2|ico)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
  <If "%{REQUEST_URI} =~ m#^/_astro/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`;
writeFileSync(join(dist, ".htaccess"), htaccess);
writeFileSync(join(dist, "version.txt"), `${process.env.GITHUB_SHA || "local"} ${new Date().toISOString()}\n`);
console.log(`postbuild: api copied, ${pageRedirects.length} page redirects, .htaccess written`);
